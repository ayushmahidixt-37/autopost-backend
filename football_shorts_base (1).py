"""## 5.1 Thumbnail Generator

YouTube Shorts auto-picks a frame as the thumbnail, but a custom "stat card" thumbnail
(big number/score + short label) tends to perform better in feeds and search.

This generates a simple branded thumbnail using Pillow: a dark background, a large headline
stat or score pulled from the script's overlays, and the category as a small label.
Output is a 1080x1920 JPEG (matches Shorts aspect ratio; YouTube also accepts this for
the custom thumbnail set via `videos.thumbnails.set`, though it will be cropped for
display in some surfaces).
"""

from PIL import Image, ImageDraw, ImageFont

THUMBNAIL_PATH = "/content/pipeline/output/thumbnail.jpg"

def make_thumbnail(headline_text, subtext, category_label, out_path,
                    width=1080, height=1920, bg_color=(15, 20, 35)):
    img = Image.new("RGB", (width, height), color=bg_color)
    draw = ImageDraw.Draw(img)

    # Try a bold system font, fall back to default if unavailable
    try:
        headline_font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 110)
        sub_font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 60)
        label_font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 40)
    except OSError:
        headline_font = ImageFont.load_default()
        sub_font = ImageFont.load_default()
        label_font = ImageFont.load_default()

    # Accent bar
    draw.rectangle([(0, 0), (width, 18)], fill=(0, 200, 120))

    # Category label, top-left
    draw.text((50, 60), category_label.upper().replace("_", " "), font=label_font, fill=(0, 200, 120))

    # Headline text, centered, word-wrapped
    def wrap_text(text, font, max_width):
        words = text.split()
        lines, current = [], ""
        for w in words:
            test = (current + " " + w).strip()
            bbox = draw.textbbox((0, 0), test, font=font)
            if bbox[2] - bbox[0] <= max_width:
                current = test
            else:
                lines.append(current)
                current = w
        if current:
            lines.append(current)
        return lines

    lines = wrap_text(headline_text, headline_font, width - 100)
    line_height = 130
    total_height = len(lines) * line_height
    start_y = (height - total_height) // 2

    for i, line in enumerate(lines):
        bbox = draw.textbbox((0, 0), line, font=headline_font)
        text_w = bbox[2] - bbox[0]
        x = (width - text_w) // 2
        y = start_y + i * line_height
        draw.text((x, y), line, font=headline_font, fill=(255, 255, 255))

    # Subtext near bottom
    if subtext:
        bbox = draw.textbbox((0, 0), subtext, font=sub_font)
        text_w = bbox[2] - bbox[0]
        x = (width - text_w) // 2
        draw.text((x, height - 220), subtext, font=sub_font, fill=(200, 200, 200))

    img.save(out_path, quality=90)
    return out_path

