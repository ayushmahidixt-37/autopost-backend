"""## 6. Word-level captions with Whisper

Transcribes the voiceover with word-level timestamps so captions can appear synced, then burns them into the video using FFmpeg's `drawtext` (via an SRT/ASS subtitle file for cleaner styling).
"""

import whisper

model = whisper.load_model("base")  # 'tiny' is faster, 'small'/'base' more accurate
result = model.transcribe(AUDIO_PATH, word_timestamps=True)

# Flatten word-level segments
words = []
for segment in result['segments']:
    for w in segment.get('words', []):
        words.append({"word": w['word'].strip(), "start": w['start'], "end": w['end']})

print(f"Transcribed {len(words)} words")
print(words[:10])

# Build an ASS subtitle file with bold, centered, animated-feel captions
# Groups words into short chunks (2-4 words) for punchy Shorts-style captions

ASS_PATH = "/content/pipeline/assets/captions.ass"

def format_ass_time(seconds):
    h = int(seconds // 3600)
    m = int((seconds % 3600) // 60)
    s = seconds % 60
    return f"{h}:{m:02d}:{s:05.2f}"

# Group words into chunks of ~3
CHUNK_SIZE = 3
chunks = []
for i in range(0, len(words), CHUNK_SIZE):
    chunk_words = words[i:i+CHUNK_SIZE]
    if not chunk_words:
        continue
    text = " ".join(w['word'] for w in chunk_words)
    chunks.append({
        "start": chunk_words[0]['start'],
        "end": chunk_words[-1]['end'],
        "text": text
    })

ass_header = """[Script Info]
ScriptType: v4.00+
PlayResX: 1080
PlayResY: 1920

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Caption,Montserrat,90,&H00FFFFFF,&H00FFFFFF,&H00000000,&H00000000,1,0,0,0,100,100,0,0,1,4,2,2,60,60,500,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""

events = []
for c in chunks:
    start = format_ass_time(c['start'])
    end = format_ass_time(c['end'])
    text = c['text'].upper()
    events.append(f"Dialogue: 0,{start},{end},Caption,,0,0,0,,{text}")

with open(ASS_PATH, 'w') as f:
    f.write(ass_header)
    f.write("\n".join(events))

print("Subtitle file written:", ASS_PATH)
print(f"{len(chunks)} caption chunks")

