def make_fingerprint(text, category=None):
    """Lowercase, strip punctuation, sort words -> rough content fingerprint.
    Two titles about the same fixture/topic usually share most key words
    even if phrased differently."""
    words = re.findall(r"[a-z0-9]+", text.lower())
    stop = {"the", "a", "an", "vs", "and", "for", "in", "of", "to", "world", "cup", "2026"}
    keywords = sorted(w for w in words if w not in stop and len(w) > 2)
    fp = "-".join(keywords)
    if category:
        fp = f"{category}:{fp}"
    return fp

def fingerprint_overlap(fp1, fp2, threshold=0.6):
    """Returns True if two fingerprints share enough keywords to be considered duplicates."""
    set1, set2 = set(fp1.split("-")), set(fp2.split("-"))
    if not set1 or not set2:
        return False
    overlap = len(set1 & set2) / min(len(set1), len(set2))
    return overlap >= threshold

